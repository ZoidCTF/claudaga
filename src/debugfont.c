/* Direct lookup, built once from the picture table above. */
static const Glyph *s_index[128];
static bool s_indexed = false;

static void build_index(void)
{
    if (s_indexed) return;
    for (int i = 0; i < ARRAY_COUNT(GLYPHS); ++i) {
        unsigned char c = (unsigned char)GLYPHS[i].ch;
        if (c < 128) s_index[c] = &GLYPHS[i];
    }
    s_indexed = true;
}

static char upcase(char c)
{
    return (c >= 'a' && c <= 'z') ? (char)(c - 'a' + 'A') : c;
}

void font_draw(Gfx *g, int x, int y, SDL_Color c, const char *text)
{
    build_index();
    SDL_SetRenderDrawColor(g->renderer, c.r, c.g, c.b, c.a);

    /* One rect per lit pixel, collected so the whole string is a single call.
       A label tops out around a hundred pixels, so the buffer is generous. */
    SDL_Rect pixels[FONT_W * FONT_H * 64];
    int n = 0;
    int pen = x;

    for (const char *p = text; *p; ++p) {
        unsigned char ch = (unsigned char)upcase(*p);
        const Glyph *gl = (ch < 128) ? s_index[ch] : NULL;
        if (gl) {
            for (int row = 0; row < FONT_H; ++row) {
                for (int col = 0; col < FONT_W; ++col) {
                    if (gl->row[row][col] != '#') continue;
                    if (n >= ARRAY_COUNT(pixels)) goto flush;
                    pixels[n].x = pen + col;
                    pixels[n].y = y + row;
                    pixels[n].w = 1;
                    pixels[n].h = 1;
                    ++n;
                }
            }
        }
        pen += FONT_ADVANCE;
    }
flush:
    if (n > 0) SDL_RenderFillRects(g->renderer, pixels, n);
}

int font_width(const char *text)
{
    int len = (int)strlen(text);
    return len > 0 ? len * FONT_ADVANCE - 1 : 0;
}
